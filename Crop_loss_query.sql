CREATE DATABASE IF NOT EXISTS my_project;
USE my_project;
-- for farmers details
CREATE TABLE Farmer (
    farmer_id INT PRIMARY KEY AUTO_INCREMENT,
    farmer_name VARCHAR(100) NOT NULL,
    phone VARCHAR(15),
    location VARCHAR(100)
);
-- for farming land details
CREATE TABLE Farm (
    farm_id INT PRIMARY KEY AUTO_INCREMENT,
    farmer_id INT NOT NULL,
    farm_name VARCHAR(100),
    location VARCHAR(100),
    area_acres DECIMAL(8,2),
    FOREIGN KEY (farmer_id) REFERENCES Farmer(farmer_id)
);
-- for crops details
CREATE TABLE Crop (
    crop_id INT PRIMARY KEY AUTO_INCREMENT,
    crop_name VARCHAR(100) NOT NULL,
    crop_type VARCHAR(50),
    season VARCHAR(50)
);
-- for cultivation details include (harvesting)
CREATE TABLE Cultivation (
    cultivation_id INT PRIMARY KEY AUTO_INCREMENT,
    farm_id INT NOT NULL,
    crop_id INT NOT NULL,
    sowing_date DATE,
    expected_yield DECIMAL(10,2),
    harvest_date DATE,
    actual_yield DECIMAL(10,2),
    CONSTRAINT cultivation_farm
    FOREIGN KEY (farm_id) REFERENCES Farm(farm_id),
    CONSTRAINT cultivation_crop
    FOREIGN KEY (crop_id) REFERENCES Crop(crop_id)
);
-- for the crop loss 
CREATE TABLE Crop_Loss (
    loss_id INT PRIMARY KEY AUTO_INCREMENT,
    cultivation_id INT NOT NULL,
    reason_id INT NOT NULL,
    loss_date DATE,
    loss_quantity DECIMAL(10,2),
    loss_percentage DECIMAL(5,2),
    FOREIGN KEY (cultivation_id) REFERENCES Cultivation(cultivation_id),
    FOREIGN KEY ( reason_id) REFERENCES Loss_Reason ( reason_id)
);
-- for analyze the loss of crops
CREATE TABLE Loss_Reason (
    reason_id INT PRIMARY KEY AUTO_INCREMENT,
    reason_name VARCHAR(100) NOT NULL,
    description VARCHAR(255)
);
-- for give the solution
CREATE TABLE Prevention_Measure (
    prevention_id INT PRIMARY KEY AUTO_INCREMENT,
    reason_id INT NOT NULL,
    prevention_action VARCHAR(255) NOT NULL,
    FOREIGN KEY (reason_id) REFERENCES Loss_Reason(reason_id)
);
